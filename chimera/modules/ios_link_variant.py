"""
chimera/modules/ios_link_variant.py
───────────────────────────────────────────────────────────────────────────────
iOS/Karing-совместимый вариант готовой VLESS-ссылки.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ПАТЧ СУЩЕСТВУЮЩИХ ГЕНЕРАТОРОВ
-----------------------------------------------------------------
Симптом «Hiddify работает на iOS, Karing — нет, на Android/ПК всё ок»
имеет два правдоподобных корня (подтверждено внешним багрепортом
KaringX/karing#1158 для первого, и общим знанием строгости iOS-парсеров
для второго):

  1. `&flow=xtls-rprx-vision` в REALITY-ссылке. XTLS Vision использует
     syscall-трюки (TCP splicing / direct read), которые в sandboxed
     iOS-приложении недоступны — sing-box под капотом Karing рвёт
     соединение через 20-40 секунд. Hiddify либо вырезает flow заранее,
     либо делает fallback.

  2. Сырой эмодзи-флаг страны в начале `#fragment` (формируется в
     `_users_gen_link` и `_gen_vless_link` как `_flag_prefix =
     f"{_flag} " ...`). iOS URL-парсеры исторически капризны к non-ASCII
     в fragment даже после percent-encoding. Это belt-and-suspenders
     гипотеза — стоимость нулевая.

Оба момента — чистая постобработка уже готовой строки ссылки. Логику
сборки host/port/pbk/sid/domain НЕ дублируем: вызываем существующий
генератор и прогоняем результат через `to_ios_karing_link()`.

Подключение — в 4 местах (см. CHANGELOG):
  • users_manager.py — _users_gen_link_ios, do_user_show_link_ios,
    generate_client_links_ios (обёртки над существующими функциями).
  • client_config_export.py — доп. файл vless-link-ios.txt рядом со
    стандартным vless-link.txt.
  • subscription.py — отдельный маршрут `/sub/{token}/ios`, тело
    собирается через build_subscription_body_ios().

API
---
    to_ios_karing_link(link: str) -> str

  На вход — любой валидный vless://. На выходе — то же самое, но без
  `&flow=xtls-rprx-vision` и без эмодзи-флага в начале `#fragment`.
  Для xHTTP-ссылок (без flow и, как правило, без эмодзи) — фактически
  no-op. Если фрагмента нет вовсе — тоже no-op.
───────────────────────────────────────────────────────────────────────────────
"""
from __future__ import annotations

import re

# Regional-indicator symbol letters: U+1F1E6 .. U+1F1FF. Пара таких
# code points изображает национальный флаг (например, 🇩🇪 = U+1F1E9
# U+1F1EA). После флага в `_flag_prefix` идёт пробел — матчим пару +
# ровно один последующий пробел, чтобы не зацепить что-то другое.
#
# `re.UNICODE` включён по умолчанию в Python 3 для str-паттернов, но мы
# используем явные code point ranges, чтобы не зависеть от `\w` и
# locale-специфичных классов.
_FLAG_EMOJI_RE = re.compile(
    r"[\U0001F1E6-\U0001F1FF]{2}\s"
)


def to_ios_karing_link(link: str) -> str:
    """iOS/Karing-совместимый вариант готовой vless-ссылки.

    Трансформации (каждая — no-op если соответствующего куска нет):
      • Убирает `&flow=xtls-rprx-vision` (REALITY-only). В xHTTP-ветках
        этого параметра нет, замена просто ничего не делает.
      • В `#fragment` убирает сырой эмодзи-флаг страны + следующий за
        ним пробел, если они есть в самом начале fragment. Email
        (percent-encoded) после флага НЕ трогается.

    Аргументы:
        link: готовая vless://-ссылка от любого генератора проекта.

    Возвращает:
        Ту же строку с описанными правками. Никогда не бросает
        исключение на обычных входах — если `link` пустой или не
        содержит `#`, возвращается как есть.
    """
    # 1. REALITY-flow вырезается по всей строке. В xHTTP-ветках его
    #    физически нет, replace() отработает как no-op. Параметр всегда
    #    стоит в виде `&flow=xtls-rprx-vision` (префикс `&` — он не
    #    первый в query), поэтому удаляем вместе с амперсандом, чтобы
    #    не оставлять `&&` или висячего `&` в начале query.
    link = link.replace("&flow=xtls-rprx-vision", "")

    # 2. Эмодзи-флаг. partition() — самый безопасный способ отделить
    #    fragment: он НЕ падает, если `#` отсутствует (в этом случае
    #    base=вся_строка, sep="", frag=""), и не делает regex-поиск
    #    по base, что было бы чревато (host/port/email-часть могут
    #    содержать любые символы).
    base, sep, frag = link.partition("#")
    if sep:
        # count=1 — строго одно срабатывание в начале fragment.
        # Если по какой-то случайности эмодзи-паттерн встретится ещё
        # раз (например, в email после quote() — что физически
        # невозможно, но фиксируем поведение), второй раз не трогаем.
        frag = _FLAG_EMOJI_RE.sub("", frag, count=1)

    return base + sep + frag
