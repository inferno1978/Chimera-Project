    print(f"  Domain:     {state.get('domain', '?')}")
    print(f"  Listen:     {state.get('listen_address', '?')}  (TCP+UDP)")
    print(f"  Cert:       {state.get('cert_chain_path', '?')}")
    print(f"  Metrics:    http://127.0.0.1:{state.get('metrics_port', _METRICS_PORT)}/metrics")
