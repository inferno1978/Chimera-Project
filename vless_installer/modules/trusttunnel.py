def _check_domain_available(domain: str) -> str:
    """D7: Check that domain is not used by another protocol.
    Returns "" if available, error message string if taken.
    """
    if not domain:
        return "domain is required"
    try:
        core = _core_module()
        # Check VLESS domain
        vless_domain = getattr(core, "PARAM_DOMAIN", "")
        if vless_domain and vless_domain == domain:
            return f"домен {domain} уже используется VLESS (PARAM_DOMAIN)"
        # Check NaiveProxy
        try:
            naive_state = json.loads(Path("/var/lib/xray-installer/naiveproxy.json").read_text())
            if naive_state.get("installed") and naive_state.get("domain") == domain:
                return f"домен {domain} уже используется NaiveProxy"
        except Exception:
            pass
        # Check FPTN
        try:
            fptn_state = json.loads(Path("/var/lib/xray-installer/fptn.json").read_text())
            if fptn_state.get("installed") and fptn_state.get("domain") == domain:
                return f"домен {domain} уже используется FPTN"
        except Exception:
            pass
        # Check MTProto own-site
        try:
            telemt_toml = Path("/etc/telemt/telemt.toml")
            if telemt_toml.exists():
                # crude grep for domain
                text = telemt_toml.read_text()
                if f'"{domain}"' in text or f"'{domain}'" in text:
                    return f"домен {domain} уже используется MTProto/Telemt"
        except Exception:
            pass
    except Exception as e:
        _log("WARN", f"_check_domain_available: {e}")
    return ""


def _check_port_available(port: int) -> str:
    """D2: Check that port is not used by another protocol.
    Returns "" if available, error message string if taken.
    """
    try:
        core = _core_module()
        if hasattr(core, "check_port_used_by_other_protocol"):
            return core.check_port_used_by_other_protocol(port, exclude_module="trusttunnel")
    except Exception as e:
        _log("WARN", f"_check_port_available: {e}")
    return ""


def _open_port(port: int) -> bool:
    """Open TCP+UDP port in ufw (or iptables fallback)."""
    try:
        if shutil.which("ufw"):
            for proto in ("tcp", "udp"):
                subprocess.run(
                    ["ufw", "allow", f"{port}/{proto}", "comment", "TRUSTTUNNEL"],
                    capture_output=True, timeout=10,
                )
            return True
    except Exception as e:
        _log("WARN", f"_open_port: ufw failed: {e}")
    # iptables fallback
    try:
        for proto in ("tcp", "udp"):
            subprocess.run(
                ["iptables", "-I", "INPUT", "1", "-p", proto,
                 "--dport", str(port), "-j", "ACCEPT"],
                capture_output=True, timeout=10,
            )
        return True
    except Exception as e:
        _log("ERROR", f"_open_port: iptables failed: {e}")
        return False


def _close_port(port: int) -> None:
    """Close TCP+UDP port in ufw (or iptables fallback)."""
    try:
        if shutil.which("ufw"):
            for proto in ("tcp", "udp"):
                subprocess.run(
                    ["ufw", "delete", "allow", f"{port}/{proto}"],
                    capture_output=True, timeout=10,
                )
            return
    except Exception:
        pass
    try:
        for proto in ("tcp", "udp"):
            subprocess.run(
                ["iptables", "-D", "INPUT", "-p", proto,
                 "--dport", str(port), "-j", "ACCEPT"],
                capture_output=True, timeout=10,
            )
    except Exception:
        pass


def _download_and_install_binary() -> Tuple[bool, str]:
    """Download prebuilt TrustTunnel binaries via download_manager.
    Returns (success, version_or_errormsg).
    """
    try:
        from vless_installer.modules.download_manager import fetch_package
        from vless_installer.modules.trusttunnel_packages import TRUSTTUNNEL_SPEC
        ok = fetch_package(TRUSTTUNNEL_SPEC, tag=f"v{_VERSION_PIN}", dry_run=False)
        if not ok:
            return False, "fetch_package failed — see logs above for manual hint"
        # Verify binary exists and is executable
        if not _BINARY_PATH.exists():
            return False, f"binary not found at {_BINARY_PATH} after fetch"
        _BINARY_PATH.chmod(0o755)
        if _WIZARD_PATH.exists():
            _WIZARD_PATH.chmod(0o755)
        # Get version
        try:
            r = subprocess.run([str(_BINARY_PATH), "--version"],
                               capture_output=True, text=True, timeout=5)
            version = r.stdout.strip() or _VERSION_PIN
        except Exception:
            version = _VERSION_PIN
        return True, version
    except Exception as e:
        return False, f"download failed: {e}"


def _import_gpg_key() -> bool:
    """Import the AdGuard GPG key for binary signature verification."""
    try:
        r = subprocess.run(
            ["gpg", "--keyserver", _GPG_KEY_SERVER, "--recv-keys", _GPG_KEY_ID],
            capture_output=True, text=True, timeout=30,
        )
        return r.returncode == 0
    except Exception as e:
        _log("WARN", f"_import_gpg_key: {e}")
        return False


def _verify_gpg_signature(binary_path: Path) -> bool:
    """Verify the GPG signature of a binary. Returns True if valid."""
    sig_path = binary_path.with_suffix(binary_path.suffix + ".sig")
    if not sig_path.exists():
        _log("WARN", f"_verify_gpg_signature: no .sig file at {sig_path}")
        return False
    try:
        r = subprocess.run(
            ["gpg", "--verify", str(sig_path), str(binary_path)],
            capture_output=True, text=True, timeout=15,
        )
        return r.returncode == 0
    except Exception as e:
        _log("WARN", f"_verify_gpg_signature: {e}")
        return False


