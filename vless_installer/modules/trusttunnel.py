def trusttunnel_load_state() -> dict:
    """Load /var/lib/xray-installer/trusttunnel.json. Returns {} if missing."""
    try:
        if _STATE_FILE.exists():
            data = json.loads(_STATE_FILE.read_text())
            if isinstance(data, dict):
                return data
    except Exception as e:
        _log("WARN", f"load_state: cannot read {_STATE_FILE}: {e}")
    return {}


def trusttunnel_save_state(state: dict) -> None:
    """Atomic write to trusttunnel.json with chmod 0o600."""
    _STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    tmp = _STATE_FILE.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2, ensure_ascii=False))
    tmp.replace(_STATE_FILE)
    try:
        _STATE_FILE.chmod(0o600)
    except Exception:
        pass


def trusttunnel_is_installed() -> bool:
    """True if state['installed'] is True AND binary exists."""
    state = trusttunnel_load_state()
    return bool(state.get("installed")) and _BINARY_PATH.exists()


# =============================================================================
#  CREDENTIALS FILE CRUD (the core of the user_lifecycle integration)
# =============================================================================
# credentials.toml format (verified in Phase 0 by reading CONFIGURATION.md and
# by writing a 3-user file and generating deep-links for each):
#
#   [[client]]
#   username = "alice@example.com"
#   password = "abc123"
#
#   [[client]]
#   username = "bob@example.com"
#   password = "def456"
#   max_http2_conns = 16
#
# We parse/emit this with a minimal TOML reader/writer (no dependency on
# Python 3.11+ tomllib — the project supports older Pythons too). The format
# is simple enough: top-level array of tables, each with string keys and
# string/int values.

def _parse_credentials_toml(text: str) -> List[Dict]:
    """Minimal TOML parser for the credentials.toml format.
    Handles [[client]] blocks with username/password (strings) and
    max_http2_conns/max_http3_conns (ints). Does NOT support the full TOML
    spec — just enough for this file.
    """
    clients: List[Dict] = []
    current: Optional[Dict] = None
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line == "[[client]]":
            if current is not None:
                clients.append(current)
            current = {}
            continue
        if current is None:
            continue
        # key = "value"  or  key = 123
        m = re.match(r'^(\w+)\s*=\s*(.+)$', line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if val.startswith('"') and val.endswith('"'):
            current[key] = val[1:-1]
        elif val.startswith("'") and val.endswith("'"):
            current[key] = val[1:-1]
        elif val.isdigit():
            current[key] = int(val)
        # else: skip unknown value types
    if current is not None:
        clients.append(current)
    return clients


def _format_credentials_toml(clients: List[Dict]) -> str:
    """Serialize a list of client dicts back to credentials.toml format."""
    lines: List[str] = []
    for c in clients:
        lines.append("[[client]]")
        lines.append(f'username = "{c.get("username", "")}"')
        lines.append(f'password = "{c.get("password", "")}"')
        if "max_http2_conns" in c and c["max_http2_conns"] is not None:
            lines.append(f'max_http2_conns = {int(c["max_http2_conns"])}')
        if "max_http3_conns" in c and c["max_http3_conns"] is not None:
            lines.append(f'max_http3_conns = {int(c["max_http3_conns"])}')
        lines.append("")
    return "\n".join(lines).rstrip() + "\n" if lines else ""


def _atomic_write_text(path: Path, text: str, mode: int = 0o600) -> None:
    """Atomic write via temp file + rename. Sets file mode."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    try:
        tmp.chmod(mode)
    except Exception:
        pass
    tmp.replace(path)


def trusttunnel_list_users() -> List[Dict]:
    """Read credentials.toml, return list of client dicts.
    Returns [] if file missing or TrustTunnel not installed.
    """
    if not _CREDS_TOML.exists():
        return []
    try:
        text = _CREDS_TOML.read_text()
        return _parse_credentials_toml(text)
    except Exception as e:
        _log("ERROR", f"list_users: cannot read {_CREDS_TOML}: {e}")
        return []


def trusttunnel_user_exists(username: str) -> bool:
    """Check if a [[client]] block with the given username exists."""
    if not username:
        return False
    for c in trusttunnel_list_users():
        if c.get("username") == username:
            return True
    return False


def trusttunnel_add_user(username: str,
                          password: str,
                          max_http2_conns: Optional[int] = None,
                          max_http3_conns: Optional[int] = None) -> bool:
    """Add or update a user in credentials.toml. Idempotent (D5 requirement).

    If a [[client]] with the same username already exists, UPDATE its password
    and connection limits in place — do NOT create a duplicate block.

    Returns True on success, False on error. Does NOT restart the service —
    that's the caller's responsibility (batched via user_lifecycle).
    """
    if not username or not password:
        _log("ERROR", f"add_user: username and password required (got username={username!r})")
        return False
    try:
        clients = trusttunnel_list_users()
        # Idempotency: find existing entry by username
        found = False
        for c in clients:
            if c.get("username") == username:
                c["password"] = password
                if max_http2_conns is not None:
                    c["max_http2_conns"] = max_http2_conns
                elif "max_http2_conns" in c:
                    del c["max_http2_conns"]
                if max_http3_conns is not None:
                    c["max_http3_conns"] = max_http3_conns
                elif "max_http3_conns" in c:
                    del c["max_http3_conns"]
                found = True
                _log("INFO", f"add_user: updated existing entry for {username!r}")
                break
        if not found:
            new_entry: Dict = {"username": username, "password": password}
            if max_http2_conns is not None:
                new_entry["max_http2_conns"] = max_http2_conns
            if max_http3_conns is not None:
                new_entry["max_http3_conns"] = max_http3_conns
            clients.append(new_entry)
            _log("INFO", f"add_user: added new entry for {username!r}")
        _atomic_write_text(_CREDS_TOML, _format_credentials_toml(clients), mode=0o600)
        return True
    except Exception as e:
        _log("ERROR", f"add_user: exception for {username!r}: {e}")
        return False


def trusttunnel_remove_user(username: str) -> bool:
    """Remove a [[client]] block by username. Idempotent (no-op if not found).

    Returns True on success (including no-op), False on error.
    Does NOT restart the service — caller's responsibility.
    """
    if not username:
        return False
    try:
        clients = trusttunnel_list_users()
        new_clients = [c for c in clients if c.get("username") != username]
        if len(new_clients) == len(clients):
            _log("INFO", f"remove_user: {username!r} not found, noop")
            return True  # idempotent
        _atomic_write_text(_CREDS_TOML, _format_credentials_toml(new_clients), mode=0o600)
        _log("INFO", f"remove_user: removed {username!r}")
        return True
    except Exception as e:
        _log("ERROR", f"remove_user: exception for {username!r}: {e}")
        return False


def trusttunnel_update_user(username: str, **fields) -> bool:
    """Update specific fields (password, max_http2_conns, max_http3_conns) on
    an existing [[client]] block. Returns False if user not found.
    """
    if not username:
        return False
    try:
        clients = trusttunnel_list_users()
        found = False
        for c in clients:
            if c.get("username") == username:
                for k, v in fields.items():
                    if v is None:
                        c.pop(k, None)
                    else:
                        c[k] = v
                found = True
                break
        if not found:
            _log("WARN", f"update_user: {username!r} not found")
            return False
        _atomic_write_text(_CREDS_TOML, _format_credentials_toml(clients), mode=0o600)
        return True
    except Exception as e:
        _log("ERROR", f"update_user: exception for {username!r}: {e}")
        return False


# =============================================================================
#  DETERMINISTIC PASSWORD (D8)
# =============================================================================
def trusttunnel_derive_password(uuid_str: str) -> str:
    """Deterministic per-user password = SHA-256("trusttunnel-pass|" + uuid).

    Pattern copied from HYDRA-ULTIMATE (with a different prefix to avoid any
    collision if a user migrates between projects). Stable across reinstalls.
    Returns a 64-char lowercase hex string.
    """
    if not uuid_str:
        raise ValueError("uuid is required to derive TrustTunnel password")
    return hashlib.sha256(b"trusttunnel-pass|" + uuid_str.encode("utf-8")).hexdigest()


# =============================================================================
#  DEEP-LINK CODEC (pure Python, upstream tt://?<base64url-TLV> format)
# =============================================================================
# TLV wire format (verified in Phase 0 by reading deeplink/src/types.rs and
# by decoding a real deep-link with scripts/deeplink_to_config.py):
#   Each entry: varint(Tag) || varint(Length) || Value[Length bytes]
#   Varint is RFC 9000 §16 QUIC varint (2-bit length prefix, big-endian).
#
# Tag values:
#   0x00 version         (VarInt, default 1)
#   0x01 hostname        (UTF-8 string)        REQUIRED
#   0x02 addresses       (UTF-8 "host:port")   REQUIRED, may repeat
#   0x03 custom_sni      (UTF-8 string)
#   0x04 has_ipv6        (1 byte bool, default True)
#   0x05 username        (UTF-8 string)        REQUIRED
#   0x06 password        (UTF-8 string)        REQUIRED
#   0x07 skip_verification (1 byte bool)
#   0x08 certificate     (DER bytes, concatenated)
#   0x09 upstream_protocol (VarInt: 1=http2, 2=http3, default 1)
#   0x0A anti_dpi        (1 byte bool)
#   0x0B client_random_prefix (UTF-8 hex string)
#   0x0C name            (UTF-8 string, display name)
#   0x0D dns_upstreams   (varint-length-prefixed UTF-8 strings, concatenated)

_TT_VERSION = 1


def _varint_encode(n: int) -> bytes:
    """RFC 9000 §16 QUIC varint encoding (2-bit length prefix, big-endian)."""
    if n < 0:
        raise ValueError("varint cannot be negative")
    if n < 64:           # 6 bits, prefix 00
        return bytes([n])
    elif n < 16384:      # 14 bits, prefix 01
        return bytes([0x40 | (n >> 8), n & 0xFF])
    elif n < 1073741824: # 30 bits, prefix 10
        return bytes([0x80 | (n >> 24), (n >> 16) & 0xFF, (n >> 8) & 0xFF, n & 0xFF])
    elif n < 4611686018427387904:  # 62 bits, prefix 11
        return bytes([0xC0 | (n >> 56), (n >> 48) & 0xFF, (n >> 40) & 0xFF,
                      (n >> 32) & 0xFF, (n >> 24) & 0xFF, (n >> 16) & 0xFF,
                      (n >> 8) & 0xFF, n & 0xFF])
    else:
        raise ValueError("varint too large")


def _varint_decode(data: bytes, offset: int) -> Tuple[int, int]:
    """Decode a QUIC varint. Returns (value, new_offset)."""
    if offset >= len(data):
        raise ValueError("varint: unexpected end of data")
    first = data[offset]
    prefix = (first & 0xC0) >> 6
    if prefix == 0:
        return first & 0x3F, offset + 1
    elif prefix == 1:
        if offset + 1 >= len(data):
            raise ValueError("varint: truncated")
        return ((first & 0x3F) << 8) | data[offset + 1], offset + 2
    elif prefix == 2:
        if offset + 3 >= len(data):
            raise ValueError("varint: truncated")
        val = ((first & 0x3F) << 24) | (data[offset+1] << 16) | \
              (data[offset+2] << 8) | data[offset+3]
        return val, offset + 4
    else:  # prefix == 3
        if offset + 7 >= len(data):
            raise ValueError("varint: truncated")
        val = 0
        for i in range(8):
            if i == 0:
                val = (first & 0x3F) << (56 - i*8)
            else:
                val |= data[offset + i] << (56 - i*8)
        return val, offset + 8


def _tlv_encode(tag: int, value: bytes) -> bytes:
    """Encode a single TLV entry: varint(tag) || varint(len) || value."""
    return _varint_encode(tag) + _varint_encode(len(value)) + value


def _b64url_no_pad(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode("ascii").rstrip("=")


def _b64url_decode_no_pad(s: str) -> bytes:
    pad = "=" * (-len(s) % 4)
    return base64.urlsafe_b64decode(s + pad)


def trusttunnel_deeplink_encode(hostname: str,
                                addresses: List[str],
                                username: str,
                                password: str,
                                custom_sni: str = "",
                                has_ipv6: bool = True,
                                skip_verification: bool = False,
                                certificate_der: bytes = b"",
                                upstream_protocol: str = "http2",
                                anti_dpi: bool = False,
                                client_random_prefix: str = "",
                                name: str = "",
                                dns_upstreams: Optional[List[str]] = None) -> str:
    """Build a tt://?<base64url> deep-link URI using the upstream TLV format.

    This is a pure-Python reimplementation of deeplink/src/encode.rs. It lets
    linkqr_lib.py generate URIs without spawning the 17 MB endpoint binary on
    every /config or /qr request.

    For Let's Encrypt certs (system-verifiable), leave certificate_der empty —
    the upstream encoder omits tag 0x08 in that case, keeping the URI compact.
    """
    payload = b""
    # 0x00 version
    payload += _tlv_encode(0x00, _varint_encode(_TT_VERSION))
    # 0x01 hostname (required)
    payload += _tlv_encode(0x01, hostname.encode("utf-8"))
    # 0x02 addresses (required, may repeat — one TLV per address)
    for addr in addresses:
        payload += _tlv_encode(0x02, addr.encode("utf-8"))
    # 0x03 custom_sni (optional, omit if empty)
    if custom_sni:
        payload += _tlv_encode(0x03, custom_sni.encode("utf-8"))
    # 0x04 has_ipv6 (optional, default True — only emit if False to match upstream)
    if not has_ipv6:
        payload += _tlv_encode(0x04, bytes([0]))
    # 0x05 username (required)
    payload += _tlv_encode(0x05, username.encode("utf-8"))
    # 0x06 password (required)
    payload += _tlv_encode(0x06, password.encode("utf-8"))
    # 0x07 skip_verification (optional)
    if skip_verification:
        payload += _tlv_encode(0x07, bytes([1]))
    # 0x08 certificate (optional — only for self-signed)
    if certificate_der:
        payload += _tlv_encode(0x08, certificate_der)
    # 0x09 upstream_protocol (optional, default http2=1)
    proto_val = 2 if upstream_protocol == "http3" else 1
    if proto_val != 1:
        payload += _tlv_encode(0x09, _varint_encode(proto_val))
    # 0x0A anti_dpi (optional)
    if anti_dpi:
        payload += _tlv_encode(0x0A, bytes([1]))
    # 0x0B client_random_prefix (optional)
    if client_random_prefix:
        payload += _tlv_encode(0x0B, client_random_prefix.encode("utf-8"))
    # 0x0C name (optional)
    if name:
        payload += _tlv_encode(0x0C, name.encode("utf-8"))
    # 0x0D dns_upstreams (optional)
    if dns_upstreams:
        dns_blob = b""
        for dns in dns_upstreams:
            dns_bytes = dns.encode("utf-8")
            dns_blob += _varint_encode(len(dns_bytes)) + dns_bytes
        payload += _tlv_encode(0x0D, dns_blob)
    return "tt://?" + _b64url_no_pad(payload)


def trusttunnel_deeplink_decode(uri: str) -> Dict:
    """Decode a tt://?<base64url> URI into a dict of fields.

    Returns dict with keys: version, hostname, addresses (list), custom_sni,
    has_ipv6, username, password, skip_verification, certificate_der (bytes),
    upstream_protocol, anti_dpi, client_random_prefix, name, dns_upstreams (list).
    """
    s = uri.strip()
    # Accept both tt://?... and tt://... (v1.0.13 backward compat)
    if s.startswith("tt://?"):
        s = s[len("tt://?"):]
    elif s.startswith("tt://"):
        s = s[len("tt://"):]
    else:
        raise ValueError(f"not a tt:// URI: {uri[:40]}...")
    data = _b64url_decode_no_pad(s)
    result: Dict = {
        "version": 0,
        "hostname": "",
        "addresses": [],
        "custom_sni": "",
        "has_ipv6": True,
        "username": "",
        "password": "",
        "skip_verification": False,
        "certificate_der": b"",
        "upstream_protocol": "http2",
        "anti_dpi": False,
        "client_random_prefix": "",
        "name": "",
        "dns_upstreams": [],
    }
    offset = 0
    while offset < len(data):
        tag, offset = _varint_decode(data, offset)
        length, offset = _varint_decode(data, offset)
        if offset + length > len(data):
            raise ValueError(f"TLV tag {tag}: length {length} exceeds remaining data")
        value = data[offset:offset + length]
        offset += length
        if tag == 0x00:
            v, _ = _varint_decode(value, 0)
            result["version"] = v
        elif tag == 0x01:
            result["hostname"] = value.decode("utf-8")
        elif tag == 0x02:
            result["addresses"].append(value.decode("utf-8"))
        elif tag == 0x03:
            result["custom_sni"] = value.decode("utf-8")
        elif tag == 0x04:
            result["has_ipv6"] = bool(value[0]) if value else False
        elif tag == 0x05:
            result["username"] = value.decode("utf-8")
        elif tag == 0x06:
            result["password"] = value.decode("utf-8")
        elif tag == 0x07:
            result["skip_verification"] = bool(value[0]) if value else False
        elif tag == 0x08:
            result["certificate_der"] = value
        elif tag == 0x09:
            v, _ = _varint_decode(value, 0)
            result["upstream_protocol"] = "http3" if v == 2 else "http2"
        elif tag == 0x0A:
            result["anti_dpi"] = bool(value[0]) if value else False
        elif tag == 0x0B:
            result["client_random_prefix"] = value.decode("utf-8")
        elif tag == 0x0C:
            result["name"] = value.decode("utf-8")
        elif tag == 0x0D:
            # list of varint-length-prefixed UTF-8 strings
            up = []
            o = 0
            while o < len(value):
                slen, o = _varint_decode(value, o)
                if o + slen > len(value):
                    break
                up.append(value[o:o+slen].decode("utf-8"))
                o += slen
            result["dns_upstreams"] = up
    return result


def trusttunnel_generate_deeplink(username: str,
                                  address: Optional[str] = None,
                                  state: Optional[dict] = None) -> str:
    """Generate a deep-link by shelling out to the endpoint binary.

    This is the "ground truth" path — uses the real upstream binary which
    embeds the server's actual cert chain when needed. Used by the install
    wizard / status display. For high-frequency bot /config requests, use
    trusttunnel_deeplink_for_user() instead (pure Python).

    Raises ValueError if the user doesn't exist in credentials.toml (D4
    requirement: non-existent user protection — avoids Rust panic).
    """
    if not trusttunnel_user_exists(username):
        raise ValueError(
            f"TrustTunnel user {username!r} not found in credentials.toml — "
            f"refusing to invoke endpoint binary (would Rust panic)"
        )
    if state is None:
        state = trusttunnel_load_state()
    if not state.get("installed"):
        raise RuntimeError("TrustTunnel not installed")
    vpn_toml = state.get("vpn_toml", str(_VPN_TOML))
    hosts_toml = state.get("hosts_toml", str(_HOSTS_TOML))
    if not address:
        # Build address from state: domain:port
        domain = state.get("domain", "")
        port = state.get("listen_port", _DEFAULT_PORT)
        address = f"{domain}:{port}" if domain else f"0.0.0.0:{port}"
    cmd = [
        str(_BINARY_PATH), vpn_toml, hosts_toml,
        "-c", username,
        "-a", address,
        "--format", "deeplink",
    ]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=15)
    except Exception as e:
        raise RuntimeError(f"trusttunnel_endpoint invocation failed: {e}")
    if r.returncode != 0:
        raise RuntimeError(
            f"trusttunnel_endpoint exited {r.returncode}: {r.stderr.strip()[:200]}"
        )
    # Output: first line is the tt://?... URI, second line is a blank, third
    # line starts with "To connect on mobile...". Extract just the URI.
    for line in r.stdout.splitlines():
        line = line.strip()
        if line.startswith("tt://"):
            return line
    raise RuntimeError(f"no tt:// URI in endpoint output: {r.stdout[:200]}")


def trusttunnel_deeplink_for_user(email: str,
                                  uuid_str: str,
                                  state: Optional[dict] = None) -> str:
    """Pure-Python deep-link builder for linkqr_lib.py.

    Returns "" if TrustTunnel not installed or user not in credentials.toml.
    Uses trusttunnel_deeplink_encode() with the server's hostname + address.
    For Let's Encrypt certs (system-verifiable), certificate_der is empty —
    the URI stays compact (matches upstream behavior).
    """
    if not email or not uuid_str:
        return ""
    if state is None:
        state = trusttunnel_load_state()
    if not state.get("installed"):
        return ""
    username = email  # D8: TrustTunnel username = email (verbatim)
    if not trusttunnel_user_exists(username):
        return ""
    password = trusttunnel_derive_password(uuid_str)
    hostname = state.get("domain", "")
    if not hostname:
        return ""
    port = state.get("listen_port", _DEFAULT_PORT)
    address = f"{hostname}:{port}"
    return trusttunnel_deeplink_encode(
        hostname=hostname,
        addresses=[address],
        username=username,
        password=password,
        upstream_protocol="http2",
    )


