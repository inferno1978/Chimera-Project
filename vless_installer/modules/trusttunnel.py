def do_trusttunnel_menu() -> None:
    """Main TrustTunnel menu (called from _core.py dispatch, entry 18)."""
    # Lazy core access for colors / input helpers
    try:
        core = _core_module()
        CYAN = getattr(core, "CYAN", "")
        GREEN = getattr(core, "GREEN", "")
        YELLOW = getattr(core, "YELLOW", "")
        NC = getattr(core, "NC", "")
        warn = getattr(core, "warn", lambda m: print(m))
        ok_msg = getattr(core, "ok", lambda m: print(m))
    except Exception:
        CYAN = GREEN = YELLOW = NC = ""
        warn = lambda m: print(m)
        ok_msg = lambda m: print(m)

    state = trusttunnel_load_state()
    installed = bool(state.get("installed"))

    while True:
        print()
        print(f"{CYAN}═══ TrustTunnel {'[' + state.get('version','') + ']' if installed else '[не установлен]'} ═══{NC}")
        print(f"  {CYAN}1{NC}  {'Переустановить' if installed else 'Установить'} TrustTunnel")
        print(f"  {CYAN}2{NC}  Статус")
        print(f"  {CYAN}3{NC}  Список пользователей")
        if installed:
            print(f"  {CYAN}4{NC}  Добавить пользователя (тест)")
            print(f"  {CYAN}5{NC}  Сгенерировать deep-link для пользователя")
            print(f"  {CYAN}6{NC}  Перезапустить сервис")
            print(f"  {CYAN}7{NC}  Инструкция для клиента")
            print(f"  {CYAN}8{NC}  Удалить TrustTunnel")
        print(f"  {CYAN}0{NC}  Назад")
        print()
        try:
            choice = input(f"{CYAN}Выбор:{NC} ").strip()
        except (EOFError, KeyboardInterrupt):
            break

        if choice == "0":
            break
        elif choice == "1":
            if installed:
                print(f"{YELLOW}Переустановка удалит текущую конфигурацию.{NC}")
                domain = state.get("domain", "")
                port = state.get("listen_port", _DEFAULT_PORT)
            else:
                try:
                    domain = input("Домен (например tt.example.com): ").strip()
                    port_str = input(f"Порт [Enter={_DEFAULT_PORT}]: ").strip()
                    port = int(port_str) if port_str.isdigit() else _DEFAULT_PORT
                except (EOFError, KeyboardInterrupt):
                    continue
            acme_email = ""
            try:
                acme_email = input("Email для Let's Encrypt (Enter для пропуска): ").strip()
            except (EOFError, KeyboardInterrupt):
                pass
            if trusttunnel_install(domain, port, acme_email):
                ok_msg("TrustTunnel установлен успешно.")
            else:
                warn("Установка не удалась — см. /var/log/xray-trusttunnel.log")
            time.sleep(2)
        elif choice == "2":
            trusttunnel_show_status()
            try:
                input("\nНажмите Enter для продолжения...")
            except (EOFError, KeyboardInterrupt):
                pass
        elif choice == "3":
            users = trusttunnel_list_users()
            if not users:
                print("Пользователей нет.")
            else:
                for u in users:
                    print(f"  - {u.get('username', '?')}")
            try:
                input("\nНажмите Enter...")
            except (EOFError, KeyboardInterrupt):
                pass
        elif choice == "4" and installed:
            try:
                email = input("Email нового пользователя: ").strip()
                uuid_str = input("UUID пользователя: ").strip()
            except (EOFError, KeyboardInterrupt):
                continue
            if not email or not uuid_str:
                warn("Email и UUID обязательны")
                time.sleep(1)
                continue
            password = trusttunnel_derive_password(uuid_str)
            if trusttunnel_add_user(email, password):
                # Single manual op — restart immediately (no batching needed)
                trusttunnel_restart_service()
                ok_msg(f"Пользователь {email} добавлен")
            else:
                warn("Не удалось добавить пользователя")
            time.sleep(1)
        elif choice == "5" and installed:
            try:
                email = input("Email пользователя: ").strip()
            except (EOFError, KeyboardInterrupt):
                continue
            try:
                link = trusttunnel_generate_deeplink(email)
                print(f"\n{GREEN}Deep-link:{NC}")
                print(link)
                print(f"\nQR: https://trusttunnel.org/qr.html#tt={link[len('tt://?'):]}")
            except ValueError as e:
                warn(str(e))
            except Exception as e:
                warn(f"Ошибка: {e}")
            try:
                input("\nНажмите Enter...")
            except (EOFError, KeyboardInterrupt):
                pass
        elif choice == "6" and installed:
            if trusttunnel_restart_service():
                ok_msg("Сервис перезапущен")
            else:
                warn("Не удалось перезапустить сервис")
            time.sleep(1)
        elif choice == "7" and installed:
            trusttunnel_show_guide()
            try:
                input("\nНажмите Enter...")
            except (EOFError, KeyboardInterrupt):
                pass
        elif choice == "8" and installed:
            try:
                confirm = input("Точно удалить TrustTunnel? (yes/no): ").strip()
            except (EOFError, KeyboardInterrupt):
                continue
            if confirm.lower() == "yes":
                if trusttunnel_uninstall():
                    ok_msg("TrustTunnel удалён")
                else:
                    warn("Ошибка при удалении")
            time.sleep(1)
        else:
            warn(f"Неверный выбор: {choice}")
            time.sleep(1)
