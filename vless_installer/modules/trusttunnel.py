# =============================================================================
#  CRON — health check + traffic stats (auto-installed on install, removed on uninstall)
# =============================================================================
# Pattern follows hysteria2_watchdog.py: a wrapper script in /usr/local/bin +
# a /etc/cron.d file. Both are installed together and removed together.
#
# Two cron entries in a single file (every 5 min):
#   */5 * * * * root /usr/local/bin/trusttunnel_cron.sh health
#   */5 * * * * root /usr/local/bin/trusttunnel_cron.sh stats
#
# The wrapper script dispatches to `main.py --trusttunnel-health` /
# `main.py --trusttunnel-stats`. We use a wrapper (not direct main.py calls
# in the cron line) so that:
#   - the cron file stays short and readable,
#   - we can add PYTHONPATH/cwd setup in one place if needed,
#   - matches the hysteria2_watchdog pattern.

# Note: we use __MAIN_PY__ / __INTERVAL__ / __SCRIPT__ placeholders + .replace()
# instead of str.format() because the bash script contains ${1:-health} which
# .format() would misinterpret as a positional arg placeholder.

_SCRIPT_TEMPLATE = """\
#!/bin/bash
# TrustTunnel cron wrapper — generated by VLESS Ultimate Installer
# Usage: trusttunnel_cron.sh {health|stats}
set -e
MODE="${1:-health}"
case "$MODE" in
    health)
        /usr/bin/python3 __MAIN_PY__ --trusttunnel-health 2>>/var/log/xray-trusttunnel.log
        ;;
    stats)
        /usr/bin/python3 __MAIN_PY__ --trusttunnel-stats 2>>/var/log/xray-trusttunnel.log
        ;;
    *)
        echo "Usage: $0 {health|stats}" >&2
        exit 1
        ;;
esac
"""

_CRON_TEMPLATE = """\
# TrustTunnel cron — VLESS Ultimate Installer
# Auto-generated; do not edit manually. Removed by trusttunnel_uninstall().
SHELL=/bin/sh
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

*/__INTERVAL__ * * * * root __SCRIPT__ health
*/__INTERVAL__ * * * * root __SCRIPT__ stats
"""


def _find_project_root() -> Path:
    """Find the project root (where main.py lives).
    Tries _PROJECT_ROOT first, then walks up from this file's location.
    """
    candidates = [
        _PROJECT_ROOT,
        Path("/opt/vless-ultimate"),
        Path("/opt/vless-installer"),
        Path(__file__).resolve().parent.parent.parent,  # vless_installer/modules/X.py → root
    ]
    for c in candidates:
        if (c / "main.py").exists():
            return c
    # Fallback: assume _PROJECT_ROOT
    return _PROJECT_ROOT


def _install_cron() -> None:
    """Install cron jobs for --trusttunnel-health and --trusttunnel-stats.
    Creates /usr/local/bin/trusttunnel_cron.sh + /etc/cron.d/trusttunnel.
    Idempotent — overwrites existing files.
    """
    project_root = _find_project_root()
    main_py = project_root / "main.py"
    if not main_py.exists():
        _log("WARN", f"_install_cron: main.py not found at {main_py}, cron will not work")
    # Write wrapper script (use .replace() — see comment near _SCRIPT_TEMPLATE)
    script_text = _SCRIPT_TEMPLATE.replace("__MAIN_PY__", str(main_py))
    try:
        _SCRIPT_FILE.write_text(script_text)
        _SCRIPT_FILE.chmod(0o755)
    except Exception as e:
        _log("ERROR", f"_install_cron: cannot write {_SCRIPT_FILE}: {e}")
        return
    # Write cron file
    cron_text = _CRON_TEMPLATE.replace("__INTERVAL__", str(_CRON_INTERVAL_MIN)) \
                              .replace("__SCRIPT__", str(_SCRIPT_FILE))
    try:
        _CRON_FILE.parent.mkdir(parents=True, exist_ok=True)
        _CRON_FILE.write_text(cron_text)
        _CRON_FILE.chmod(0o644)
    except Exception as e:
        _log("ERROR", f"_install_cron: cannot write {_CRON_FILE}: {e}")
        return
    _log("INFO", f"_install_cron: installed {_CRON_FILE} (interval={_CRON_INTERVAL_MIN}min)")


def _remove_cron() -> None:
    """Remove cron jobs for TrustTunnel. Idempotent."""
    for f in (_CRON_FILE, _SCRIPT_FILE):
        if f.exists():
            try:
                f.unlink()
                _log("INFO", f"_remove_cron: removed {f}")
            except Exception as e:
                _log("WARN", f"_remove_cron: cannot remove {f}: {e}")


def trusttunnel_cron_installed() -> bool:
    """Check if the cron file is installed. Used by tests + status display."""
    return _CRON_FILE.exists() and _SCRIPT_FILE.exists()


def trusttunnel_install(domain: str,
                        port: int = _DEFAULT_PORT,
                        acme_email: str = "") -> bool:
    """Full TrustTunnel install. Returns True on success.

    Steps:
      1. Pre-flight: check domain (D7) and port (D2) availability.
      2. Download prebuilt binaries via download_manager (D6).
      3. Verify GPG signatures (D6).
      4. Obtain Let's Encrypt cert via ssl_certbot.obtain_ssl_cert (D1).
      5. Run setup_wizard in non-interactive mode with --cert-type provided.
      6. Write systemd unit with ExecReload (D9).
      7. Install certbot deploy hook (D1).
      8. Open ufw/iptables ports (D2).
      9. Install cron jobs (--trusttunnel-health + --trusttunnel-stats, every 5 min).
     10. Start service, save state.
    """
    _log("INFO", f"install: domain={domain!r}, port={port}, acme_email={acme_email!r}")

    # 1. Pre-flight checks
    if not domain:
        _log("ERROR", "install: domain is required")
        return False
    domain_err = _check_domain_available(domain)
    if domain_err:
        _log("ERROR", f"install: {domain_err}")
        return False
    port_err = _check_port_available(port)
    if port_err:
        _log("ERROR", f"install: {port_err}")
        return False

    # 2. Download binaries
    _log("INFO", "install: downloading prebuilt binaries")
    ok, version_or_err = _download_and_install_binary()
    if not ok:
        _log("ERROR", f"install: {_download_and_install_binary.__name__}: {version_or_err}")
        return False
    version = version_or_err

    # 3. GPG verify
    _log("INFO", "install: importing AdGuard GPG key")
    _import_gpg_key()
    if not _verify_gpg_signature(_BINARY_PATH):
        _log("WARN", "install: GPG signature verification failed — continuing (binary already downloaded)")
        # Non-fatal: the binary is already in place. Log and continue.

    # 4. Obtain Let's Encrypt cert (D1)
    _log("INFO", f"install: obtaining Let's Encrypt cert for {domain}")
    try:
        from vless_installer.modules.ssl_certbot import obtain_ssl_cert
        obtain_ssl_cert(domain=domain)
    except Exception as e:
        _log("ERROR", f"install: obtain_ssl_cert failed: {e}")
        return False
    cert_chain = Path(f"/etc/letsencrypt/live/{domain}/fullchain.pem")
    cert_key = Path(f"/etc/letsencrypt/live/{domain}/privkey.pem")
    if not cert_chain.exists() or not cert_key.exists():
        _log("ERROR", f"install: cert files missing at {cert_chain}")
        return False

    # 5. Run setup_wizard non-interactive with --cert-type provided (D1)
    _log("INFO", "install: running setup_wizard (non-interactive)")
    listen_addr = f"0.0.0.0:{port}"
    # setup_wizard -c takes ONE user:pass pair. We'll use a placeholder admin
    # and then overwrite credentials.toml with our real users via CRUD API.
    # (The adapter's add() will populate real users after install.)
    admin_pass = trusttunnel_derive_password("00000000-0000-0000-0000-000000000000")
    cmd = [
        str(_WIZARD_PATH),
        "-m", "non-interactive",
        "-a", listen_addr,
        "-c", f"admin:{admin_pass}",
        "-n", domain,
        "--cert-type", "provided",
        "--cert-chain-path", str(cert_chain),
        "--cert-key-path", str(cert_key),
        "--lib-settings", str(_VPN_TOML),
        "--hosts-settings", str(_HOSTS_TOML),
    ]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=60, cwd=str(_INSTALL_DIR))
    except Exception as e:
        _log("ERROR", f"install: setup_wizard invocation failed: {e}")
        return False
    if r.returncode != 0:
        _log("ERROR", f"install: setup_wizard exited {r.returncode}: {r.stderr[:300]}")
        return False

    # Append [metrics] block to vpn.toml so we can scrape /metrics (D5)
    try:
        with _VPN_TOML.open("a") as f:
            f.write(f"\n[metrics]\naddress = \"127.0.0.1:{_METRICS_PORT}\"\nrequest_timeout_secs = 3\n")
    except Exception as e:
        _log("WARN", f"install: cannot append [metrics] to vpn.toml: {e}")

    # 6. systemd unit (D9)
    _log("INFO", "install: writing systemd unit")
    _install_systemd_unit(_INSTALL_DIR)

    # 7. Cert renewal hook (D1)
    _install_cert_renewal_hook()

    # 8. Open ports (D2)
    _log("INFO", f"install: opening ports {port}/tcp + {port}/udp")
    _open_port(port)

    # 9. Install cron jobs (health check + traffic stats, every 5 min)
    _log("INFO", "install: installing cron jobs")
    _install_cron()

    # 10. Start service
    _log("INFO", "install: starting service")
    try:
        subprocess.run(["systemctl", "start", _SERVICE_NAME],
                       capture_output=True, text=True, timeout=15)
    except Exception as e:
        _log("ERROR", f"install: systemctl start failed: {e}")

    # Save state
    state = {
        "installed":       True,
        "version":         version,
        "domain":          domain,
        "listen_address":  listen_addr,
        "listen_port":     port,
        "cert_type":       "provided",
        "cert_chain_path": str(cert_chain),
        "cert_key_path":   str(cert_key),
        "install_dir":     str(_INSTALL_DIR),
        "binary_path":     str(_BINARY_PATH),
        "wizard_path":     str(_WIZARD_PATH),
        "vpn_toml":        str(_VPN_TOML),
        "hosts_toml":      str(_HOSTS_TOML),
        "creds_toml":      str(_CREDS_TOML),
        "rules_toml":      str(_RULES_TOML),
        "metrics_port":    _METRICS_PORT,
        "installed_at":    datetime.now(timezone.utc).isoformat(),
    }
    trusttunnel_save_state(state)
    _log("INFO", f"install: done, version={version}, port={port}")
    return True


def trusttunnel_uninstall() -> bool:
    """Full uninstall. Returns True on success."""
    _log("INFO", "uninstall: starting")
    state = trusttunnel_load_state()
    port = state.get("listen_port", _DEFAULT_PORT)

    # Stop + remove systemd unit
    _remove_systemd_unit()

    # Close ports
    _close_port(port)

    # Remove cert renewal hook
    _remove_cert_renewal_hook()

    # Remove cron jobs (health + stats) — no hanging cron entries
    _remove_cron()

    # Remove install dir (binaries + configs)
    try:
        if _INSTALL_DIR.exists():
            shutil.rmtree(_INSTALL_DIR)
    except Exception as e:
        _log("WARN", f"uninstall: cannot remove {_INSTALL_DIR}: {e}")

    # Clear state
    try:
        _STATE_FILE.unlink()
    except Exception:
        pass
    _log("INFO", "uninstall: done")
    return True


