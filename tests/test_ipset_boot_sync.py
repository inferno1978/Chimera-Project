#!/usr/bin/env python3
"""
tests/test_ipset_boot_sync.py
───────────────────────────────────────────────────────────────────────────────
Unit-тесты для chimera/modules/ipset_boot_sync.py — бут-восстановление
ipset-определений до iptables-restore (живой кейс окт.2026 №10).

Покрывает:
  1. collect_referenced_sets — парсинг --match-set/--add-set из дампа,
     дедуп, сортировка, отсутствующие файлы
  2. sync_ipset_boot_conf — запись create+add для существующих сетов
  3. sync_ipset_boot_conf — нет set-ссылок → устаревший файл удаляется
  4. sync_ipset_boot_conf — падший ipset save пропускается, остальные
     сохраняются
  5. sync_ipset_boot_conf — нет ipset-бинарника → (False, …)
  6. restore_ipset_boot_conf — ipset restore -! -f <conf>
  7. IPSET_RESTORE_CMD_SHELL — контракт guard-строки для юнитов/rc.local
     (test -s … && ipset restore -! … || true)

Все вызовы ipset — mock'd через _fake_run. Реальных операций нет.
"""
from __future__ import annotations

import sys
import tempfile
import types
import unittest
from pathlib import Path
from unittest.mock import patch

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT))

from chimera.modules import ipset_boot_sync


def _cp(rc=0, stdout=""):
    """Fake CompletedProcess."""
    return types.SimpleNamespace(returncode=rc, stdout=stdout, stderr="")


_RULES_V4_SAMPLE = """# Generated by iptables-save
*mangle
:PREROUTING ACCEPT [0:0]
-A PREROUTING -i awg0 -m set ! --match-set awg_ru_networks dst -j awg_lb
COMMIT
*filter
:INPUT DROP [0:0]
-A INPUT -p tcp -m tcp --dport 443 -m set --match-set xray_knocked src -j ACCEPT
-A INPUT -p tcp -m tcp --dport 443 -j SET --add-set xray_knocked src
COMMIT
"""

_RULES_V6_SAMPLE = """*filter
-A INPUT -p tcp -m tcp --dport 443 -m set --match-set clients_wl_v6 src -j ACCEPT
COMMIT
"""


class TestCollectReferencedSets(unittest.TestCase):
    """Парсинг set-ссылок из дампов правил."""

    def setUp(self):
        self._tmp = Path(tempfile.mkdtemp())

    def tearDown(self):
        import shutil
        shutil.rmtree(self._tmp, ignore_errors=True)

    def test_match_and_add_set_collected_dedup_sorted(self):
        v4 = self._tmp / "rules.v4"
        v4.write_text(_RULES_V4_SAMPLE)
        v6 = self._tmp / "rules.v6"
        v6.write_text(_RULES_V6_SAMPLE)
        refs = ipset_boot_sync.collect_referenced_sets(v4, v6)
        # awg_ru_networks, xray_knocked (match+add → один), clients_wl_v6
        self.assertEqual(refs, ["awg_ru_networks", "clients_wl_v6", "xray_knocked"])

    def test_no_refs_in_clean_dump(self):
        v4 = self._tmp / "rules.v4"
        v4.write_text("*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n")
        self.assertEqual(ipset_boot_sync.collect_referenced_sets(v4), [])

    def test_missing_files_skipped(self):
        self.assertEqual(
            ipset_boot_sync.collect_referenced_sets(self._tmp / "nope.v4"), [])

    def test_del_and_query_set_also_matched(self):
        v4 = self._tmp / "rules.v4"
        v4.write_text("-A FORWARD -j SET --del-set foo src\n"
                      "-A OUTPUT -j SET --query-set bar src\n")
        self.assertEqual(ipset_boot_sync.collect_referenced_sets(v4), ["bar", "foo"])


class TestSyncIpsetBootConf(unittest.TestCase):
    """sync_ipset_boot_conf — запись boot-файла (всё через моки)."""

    def setUp(self):
        self._tmp = Path(tempfile.mkdtemp())
        self._conf = self._tmp / "ipset-boot.conf"
        self._v4 = self._tmp / "rules.v4"
        self._v6 = self._tmp / "rules.v6"
        self._v4.write_text(_RULES_V4_SAMPLE)
        self._v6.write_text(_RULES_V6_SAMPLE)

    def tearDown(self):
        import shutil
        shutil.rmtree(self._tmp, ignore_errors=True)

    def _sync(self, fake_run, which="/usr/sbin/ipset"):
        with patch.object(ipset_boot_sync, "IPSET_BOOT_CONF", self._conf), \
             patch.object(ipset_boot_sync, "RULES_V4", self._v4), \
             patch.object(ipset_boot_sync, "RULES_V6", self._v6), \
             patch.object(ipset_boot_sync, "_run", fake_run), \
             patch.object(ipset_boot_sync.shutil, "which",
                          lambda b: which if b == "ipset" else None):
            return ipset_boot_sync.sync_ipset_boot_conf()

    def test_writes_create_and_add_lines(self):
        saves = {
            "awg_ru_networks":
                "create awg_ru_networks hash:net family inet hashsize 4096 "
                "maxelem 65536\nadd awg_ru_networks 5.253.100.0/22\n",
            "clients_wl_v6":
                "create clients_wl_v6 hash:net family inet6 maxelem 100000\n",
            "xray_knocked":
                "create xray_knocked hash:ip timeout 3600\n"
                "add xray_knocked 1.2.3.4 timeout 3599\n",
        }

        def fake_run(cmd, timeout=300):
            self.assertEqual(cmd[:2], ["ipset", "save"])
            return _cp(0, saves[cmd[2]])

        ok, msg = self._sync(fake_run)
        self.assertTrue(ok, msg)
        text = self._conf.read_text()
        self.assertIn("create awg_ru_networks hash:net", text)
        self.assertIn("add awg_ru_networks 5.253.100.0/22", text)
        self.assertIn("create clients_wl_v6 hash:net family inet6", text)
        self.assertIn("add xray_knocked 1.2.3.4 timeout 3599", text)
        # порядок — по алфавиту ссылок (sorted)
        self.assertLess(text.index("awg_ru_networks"), text.index("xray_knocked"))
        # tmp-файл не остался
        self.assertFalse((self._tmp / "ipset-boot.conf.tmp").exists())

    def test_no_refs_removes_stale_conf(self):
        self._v4.write_text("*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n")
        self._v6.unlink()
        self._conf.write_text("create stale hash:ip\n")  # устаревший
        ok, msg = self._sync(lambda *a, **kw: _cp(0, ""))
        self.assertTrue(ok, msg)
        self.assertFalse(self._conf.exists(), "устаревший boot-файл должен быть удалён")

    def test_failed_save_skipped_others_saved(self):
        def fake_run(cmd, timeout=300):
            if cmd[2] == "clients_wl_v6":
                return _cp(1, "")  # сета нет в ядре
            return _cp(0, f"create {cmd[2]} hash:net\nadd {cmd[2]} 10.0.0.0/8\n")
        ok, msg = self._sync(fake_run)
        self.assertTrue(ok, msg)
        text = self._conf.read_text()
        self.assertNotIn("clients_wl_v6", text)
        self.assertIn("create awg_ru_networks", text)

    def test_all_saves_failed_returns_false(self):
        ok, msg = self._sync(lambda *a, **kw: _cp(1, ""))
        self.assertFalse(ok)
        self.assertFalse(self._conf.exists())

    def test_no_ipset_binary(self):
        ok, msg = self._sync(lambda *a, **kw: _cp(0, ""), which=None)
        self.assertFalse(ok)
        self.assertIn("ipset", msg)


class TestRestoreIpsetBootConf(unittest.TestCase):
    """restore_ipset_boot_conf — команда восстановления."""

    def setUp(self):
        self._tmp = Path(tempfile.mkdtemp())
        self._conf = self._tmp / "ipset-boot.conf"

    def tearDown(self):
        import shutil
        shutil.rmtree(self._tmp, ignore_errors=True)

    def test_missing_conf_returns_false(self):
        with patch.object(ipset_boot_sync, "IPSET_BOOT_CONF", self._conf):
            self.assertFalse(ipset_boot_sync.restore_ipset_boot_conf())

    def test_invokes_ipset_restore_force_file(self):
        self._conf.write_text("create foo hash:ip\n")
        seen = []

        def fake_run(cmd, timeout=300):
            seen.append(cmd)
            return _cp(0, "")

        with patch.object(ipset_boot_sync, "IPSET_BOOT_CONF", self._conf), \
             patch.object(ipset_boot_sync, "_run", fake_run):
            self.assertTrue(ipset_boot_sync.restore_ipset_boot_conf())
        self.assertEqual(
            seen, [["ipset", "restore", "-!", "-f", str(self._conf)]])


class TestGuardCommandContract(unittest.TestCase):
    """IPSET_RESTORE_CMD_SHELL — контракт для mtproto-юнита и rc.local."""

    def test_guard_shape(self):
        cmd = ipset_boot_sync.IPSET_RESTORE_CMD_SHELL
        # файл существует и непуст → restore; иначе — молча пропустить
        self.assertIn("test -s /etc/iptables/ipset-boot.conf", cmd)
        self.assertIn("ipset restore -! -f /etc/iptables/ipset-boot.conf", cmd)
        self.assertTrue(cmd.endswith("|| true"), "guard не должен ронять юнит/rc.local")
        # нет редиректов/пайпов, ломающих ExecStart=/bin/sh -c '…'
        self.assertNotIn("'", cmd)


if __name__ == "__main__":
    unittest.main(verbosity=2)
