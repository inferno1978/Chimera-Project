class _TrustTunnelLifecycleFixture:
    """Helper: sets up a tempdir with realistic state files and patches
    all the module-level paths so TrustTunnelAdapter operates on temp files."""

    def __init__(self):
        self.tmpdir = Path(tempfile.mkdtemp())
        self.creds_toml = self.tmpdir / "credentials.toml"
        self.state_json = self.tmpdir / "trusttunnel.json"
        self.users_json = self.tmpdir / "users.json"
        self.users_json.write_text("[]")
        self.binary_path = self.tmpdir / "trusttunnel_endpoint"
        self.binary_path.write_text("#!/bin/sh\nexit 0\n")
