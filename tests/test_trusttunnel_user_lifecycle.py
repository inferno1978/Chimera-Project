#  TEST 2: Rollback — partial failure in multi-protocol add_user
# =============================================================================
class TestRollbackOnPartialFailure(unittest.TestCase):
    """Requirement 3: TrustTunnel-синхронизация падает в середине
    мультипротокольного add_user → откатываются ВСЕ файлы, рестарт НЕ происходит."""

    def setUp(self):
        _setup_core_in_sysmodules()
        self.fx = _TrustTunnelLifecycleFixture()
        self.fx.write_creds(_REAL_CREDS_TOML)
        self.fx.write_state({
            "installed": True,
            "version": "1.0.33",
            "domain": "tt.example.com",
            "listen_port": 8443,
        })
        for p in self.fx.patches():
            p.start()
            self.addCleanup(p.stop)
        self.restart_calls = 0
        self.restart_patch = patch(
            "vless_installer.modules.trusttunnel.trusttunnel_restart_service",
            side_effect=self._count_restart,
        )
        self.restart_patch.start()
        self.addCleanup(self.restart_patch.stop)

    def tearDown(self):
        self.fx.cleanup()

    def _count_restart(self):
        self.restart_calls += 1
        return True

    def test_rollback_restores_creds_and_no_restart(self):
        """If TrustTunnel add fails AFTER VLESS add succeeds, both files
        should be rolled back AND no restart should happen."""
        from vless_installer.modules import user_lifecycle
        user_lifecycle._PENDING_RESTARTS = set()
        user_lifecycle._BATCH_DEPTH = 0

        # Save original creds for later comparison
        original_creds = self.fx.creds_toml.read_text()
        original_users = self.fx.users_json.read_text()

        # Mock VlessAdapter.add to succeed (simulates VLESS user created)
        # But then mock trusttunnel_add_user to FAIL (simulates creds.toml
        # write failure — e.g. disk full or permissions).
        with patch.object(user_lifecycle.VlessAdapter, "add", return_value=True) as mock_vless_add, \
             patch("vless_installer.modules.trusttunnel.trusttunnel_add_user",
                   side_effect=IOError("simulated disk full")):
            result = user_lifecycle.add_user(
                email="newuser@example.com",
                protocols=["vless", "trusttunnel"],
                uuid_str="55555555-5555-5555-5555-555555555555",
            )

        # add_user should have failed
        self.assertFalse(result["success"],
                         f"add_user should fail when trusttunnel.add raises, got: {result}")
        self.assertIn("trusttunnel", result["failed"])

        # credentials.toml should be UNCHANGED (rolled back)
        # Note: VlessAdapter.add was mocked to return True without actually
        # touching users.json, so users.json is also unchanged.
        self.assertEqual(self.fx.creds_toml.read_text(), original_creds,
                         "credentials.toml should be rolled back to original")
        self.assertEqual(self.fx.users_json.read_text(), original_users,
                         "users.json should be rolled back to original")

        # CRITICAL: no restart should have happened for the rolled-back
        # TrustTunnel operation.
        self.assertEqual(self.restart_calls, 0,
                         f"no restart should happen on rollback, got {self.restart_calls}")

        # _PENDING_RESTARTS should be empty (cancelled by rollback)
        self.assertEqual(user_lifecycle._PENDING_RESTARTS, set(),
                         "pending restarts should be cancelled on rollback")

    def test_rollback_when_trusttunnel_is_first_protocol(self):
        """Even if TrustTunnel is the FIRST protocol and fails, rollback
        should still work and no restart should happen."""
        from vless_installer.modules import user_lifecycle
        user_lifecycle._PENDING_RESTARTS = set()
        user_lifecycle._BATCH_DEPTH = 0

        original_creds = self.fx.creds_toml.read_text()

        with patch("vless_installer.modules.trusttunnel.trusttunnel_add_user",
                   side_effect=IOError("simulated failure")):
            result = user_lifecycle.add_user(
                email="newuser@example.com",
                protocols=["trusttunnel"],  # trusttunnel only
                uuid_str="66666666-6666-6666-6666-666666666666",
            )

        self.assertFalse(result["success"])
        self.assertEqual(self.fx.creds_toml.read_text(), original_creds,
                         "creds should be unchanged after failed add")
        self.assertEqual(self.restart_calls, 0,
                         "no restart on failed add")
        self.assertEqual(user_lifecycle._PENDING_RESTARTS, set())


