#  TEST 1: Batching — 5 users → exactly 1 restart
# =============================================================================
class TestBatchedRestarts(unittest.TestCase):
    """Requirement 2: 5 users blocked in one cron pass → exactly 1 restart,
    not 5."""

    def setUp(self):
        _setup_core_in_sysmodules()
        self.fx = _TrustTunnelLifecycleFixture()
        # Start with 5 users in credentials.toml
        creds = ""
        for i in range(5):
            creds += f'[[client]]\nusername = "user{i}@example.com"\npassword = "pass{i}"\n\n'
        self.fx.write_creds(creds.strip() + "\n")
        self.fx.write_state({
            "installed": True,
            "version": "1.0.33",
            "domain": "tt.example.com",
            "listen_port": 8443,
        })
        for p in self.fx.patches():
            p.start()
            self.addCleanup(p.stop)
        # Mock the restart function so we can count calls
        self.restart_calls = 0
        self.restart_patch = patch(
            "vless_installer.modules.trusttunnel.trusttunnel_restart_service",
            side_effect=self._count_restart,
        )
        self.restart_patch.start()
        self.addCleanup(self.restart_patch.stop)

    def tearDown(self):
        self.fx.cleanup()

    def _count_restart(self):
        self.restart_calls += 1
        return True

    def test_batch_context_collapses_5_blocks_to_1_restart(self):
        """5 block_user() calls inside batch_context → 1 restart."""
        from vless_installer.modules import user_lifecycle
        user_lifecycle._PENDING_RESTARTS = set()
        user_lifecycle._BATCH_DEPTH = 0

        # Also mock VLESS adapter (since users.json is empty, block is a noop
        # but we need it to not crash)
        with patch.object(user_lifecycle.VlessAdapter, "block", return_value=True):
            with user_lifecycle.batch_context():
                for i in range(5):
                    user_lifecycle.block_user(
                        f"user{i}@example.com",
                        reason="traffic_limit",
                        protocols=["trusttunnel"],  # skip vless to keep it simple
                    )
        # After batch_context exits, restart should have been called exactly ONCE
        self.assertEqual(self.restart_calls, 1,
                         f"expected 1 restart for 5 batched blocks, got {self.restart_calls}")

    def test_no_batch_context_5_separate_ops_5_restarts(self):
        """Without batch_context, 5 separate block_user() calls → 5 restarts.
        This confirms the batching is what collapses them."""
        from vless_installer.modules import user_lifecycle
        user_lifecycle._PENDING_RESTARTS = set()
        user_lifecycle._BATCH_DEPTH = 0

        with patch.object(user_lifecycle.VlessAdapter, "block", return_value=True):
            for i in range(5):
                # Re-write creds each iteration so the user exists for block
                creds = ""
                for j in range(5):
                    if j == i:
                        continue  # simulate the user being blocked (removed)
                    creds += f'[[client]]\nusername = "user{j}@example.com"\npassword = "pass{j}"\n\n'
                # Actually, block = remove. Let's just re-add all 5 each time
                # so the user exists when we try to block it.
                creds = ""
                for j in range(5):
                    creds += f'[[client]]\nusername = "user{j}@example.com"\npassword = "pass{j}"\n\n'
                self.fx.write_creds(creds.strip() + "\n")
                user_lifecycle.block_user(
                    f"user{i}@example.com",
                    reason="traffic_limit",
                    protocols=["trusttunnel"],
                )
        self.assertEqual(self.restart_calls, 5,
                         f"expected 5 restarts without batching, got {self.restart_calls}")

    def test_nested_batch_context_still_one_restart(self):
        """Nested batch_context() should still produce only 1 restart."""
        from vless_installer.modules import user_lifecycle
        user_lifecycle._PENDING_RESTARTS = set()
        user_lifecycle._BATCH_DEPTH = 0

        with patch.object(user_lifecycle.VlessAdapter, "block", return_value=True):
            with user_lifecycle.batch_context():
                with user_lifecycle.batch_context():
                    user_lifecycle.block_user("user0@example.com",
                                              protocols=["trusttunnel"])
                user_lifecycle.block_user("user1@example.com",
                                          protocols=["trusttunnel"])
        self.assertEqual(self.restart_calls, 1,
                         f"nested batch should produce 1 restart, got {self.restart_calls}")


