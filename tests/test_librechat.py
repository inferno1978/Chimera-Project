    def _unit_text(self, profiles):
        with patch.object(subprocess, "run", lambda *a, **k: None):
            self.assertTrue(lc._write_systemd_unit(profiles))
        return lc.LC_UNIT_PATH.read_text()

    def test_unit_structure(self):
        unit = self._unit_text([])
        self.assertIn("Type=oneshot", unit)
        self.assertIn("RemainAfterExit=yes", unit)
        self.assertIn("up -d --remove-orphans", unit)
        self.assertIn("down --remove-orphans", unit)
        self.assertIn("Requires=docker.service", unit)
        self.assertIn(str(lc.LC_COMPOSE_FILE), unit)
        # без профилей — флагов нет
