class TestContainersParser(unittest.TestCase):
    """Разбор docker compose ps --format json (строки и массив)."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        # _containers_status проверяет LC_COMPOSE_FILE.exists() — файл должен существовать
        self._compose = Path(self._tmp.name) / "docker-compose.yml"
        self._compose.write_text("services: {}")
        self._old = lc.LC_COMPOSE_FILE
        lc.LC_COMPOSE_FILE = self._compose

    def tearDown(self):
        lc.LC_COMPOSE_FILE = self._old
        self._tmp.cleanup()

    def test_parse_lines(self):
        with patch.object(lc, "_compose_run") as run:
            run.return_value = subprocess.CompletedProcess(
                [], 0, stdout='{"name":"LibreChat","state":"running","image":"x"}\n'
                             '{"name":"chat-mongodb","state":"running","image":"y"}')
            cs = lc._containers_status()
        self.assertEqual(len(cs), 2)
        self.assertEqual(cs[0]["name"], "LibreChat")
        self.assertEqual(cs[1]["state"], "running")

    def test_parse_array(self):
        with patch.object(lc, "_compose_run") as run:
            run.return_value = subprocess.CompletedProcess(
                [], 0,
                stdout='[{"Name":"LibreChat","State":"exited","Image":"x"}]')
            cs = lc._containers_status()
        self.assertEqual(len(cs), 1)
        self.assertEqual(cs[0]["name"], "LibreChat")
        self.assertEqual(cs[0]["state"], "exited")


