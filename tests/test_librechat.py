class TestComposePatch(unittest.TestCase):
    """3. Патчер compose: 6 патчей против структуры v0.8.8 + дрейф."""

    def test_all_patches_applied(self):
        patched = lc._patch_upstream_compose(_UPSTREAM_COMPOSE, "v0.8.8")
        # 1. пин релизного образа Docker Hub
        self.assertIn("image: librechat/librechat:v0.8.8", patched)
        self.assertNotIn("librechat-dev:latest", patched)
        # 2. loopback-привязка порта api
        self.assertIn('      - "127.0.0.1:${PORT}:${PORT}"', patched)
        # 3. depends_on api без rag_api
        self.assertIn("    depends_on:\n      - mongodb\n    image:", patched)
        self.assertNotIn("      - rag_api\n    image:", patched)
        # 4. профили
        self.assertIn('  rag_api:\n    container_name: rag_api\n    profiles: ["rag"]', patched)
        self.assertIn('  vectordb:\n    container_name: vectordb\n    profiles: ["rag"]', patched)
        self.assertIn('  admin-panel:\n    container_name: admin-panel\n    profiles: ["admin"]', patched)
        # 5. порт admin-panel loopback + дефолт 3100 (3000 занят AGH)
        self.assertIn('      - "127.0.0.1:${ADMIN_PANEL_PORT:-3100}:3000"', patched)
        # 6. кредит лицензии + заголовок Chimera
        self.assertTrue(patched.startswith("# Chimera LibreChat"))
        self.assertIn("MIT", patched)

    def test_repatch_raises_honestly(self):
        """Повторный патч уже-патченного файла честно падает (детект двойного
        патча), а не молча проходит — в реальном флоу _fetch_compose патчит
        только свежескачанный файл апстрима."""
        once = lc._patch_upstream_compose(_UPSTREAM_COMPOSE, "v0.8.8")
        with self.assertRaises(lc.ComposePatchError):
            lc._patch_upstream_compose(once, "v0.8.8")

    def test_header_not_duplicated(self):
        # заголовок вшивается один раз даже если вход уже с заголовком
        pre = "# Chimera LibreChat — docker-compose (upstream X, MIT).\n" + _UPSTREAM_COMPOSE
        patched = lc._patch_upstream_compose(pre, "v0.8.8")
        self.assertEqual(patched.count("# Chimera LibreChat"), 1)

    def test_version_in_image_pin(self):
        patched = lc._patch_upstream_compose(_UPSTREAM_COMPOSE, "v0.9.0-rc1")
        self.assertIn("image: librechat/librechat:v0.9.0-rc1", patched)

    def _assert_patch_drift(self, broken: str, needle: str):
        with self.assertRaises(lc.ComposePatchError) as ctx:
            lc._patch_upstream_compose(broken, "v0.8.8")
        self.assertIn(needle, str(ctx.exception))

    def test_drift_image_line(self):
        self._assert_patch_drift(
            _UPSTREAM_COMPOSE.replace(
                "image: registry.librechat.ai/librechat-ai/librechat-dev:latest",
                "image: other:1"),
            "образ")

    def test_drift_port_line(self):
        self._assert_patch_drift(
            _UPSTREAM_COMPOSE.replace('      - "${PORT}:${PORT}"', '      - "3080:3080"'),
            "loopback")

    def test_drift_depends_on(self):
        self._assert_patch_drift(
            _UPSTREAM_COMPOSE.replace("      - rag_api\n", ""),
            "depends_on")

    def test_drift_profiles(self):
        self._assert_patch_drift(
            _UPSTREAM_COMPOSE.replace("  rag_api:\n    container_name: rag_api\n", "  rag_api:\n"),
            "profile")

    def test_drift_admin_port(self):
        self._assert_patch_drift(
            _UPSTREAM_COMPOSE.replace(
                '      - "${ADMIN_PANEL_PORT:-3000}:3000"\n', ""),
            "admin-panel")


class TestEnv(unittest.TestCase):
    """4. .env: парсер, рендер, секреты переживают регенерацию."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)
        self._old_dir, self._old_env = lc.LC_INSTALL_DIR, lc.LC_ENV_FILE
        lc.LC_INSTALL_DIR = self.tmp
        lc.LC_ENV_FILE = self.tmp / ".env"

    def tearDown(self):
        lc.LC_INSTALL_DIR, lc.LC_ENV_FILE = self._old_dir, self._old_env
        self._tmp.cleanup()

    def test_parse_env_text(self):
        text = "# comment\nA=1\n\n  B = spaced  \nBROKEN LINE\nC=x=y\n"
        env = lc._parse_env_text(text)
        self.assertEqual(env, {"A": "1", "B": "spaced", "C": "x=y"})

    def test_write_env_secret_formats(self):
        env = lc._write_env(3080, 3100, [])
        # CREDS_KEY/IV — ровно 32 символа (требование апстрима AES)
        self.assertEqual(len(env["CREDS_KEY"]), 32)
        self.assertEqual(len(env["CREDS_IV"]), 32)
        self.assertTrue(len(env["JWT_SECRET"]) >= 32)
        self.assertTrue(len(env["MEILI_MASTER_KEY"]) >= 16)
        self.assertEqual(env["PORT"], "3080")
        self.assertEqual(env["UID"], "1000")
        self.assertEqual(env["MONGO_URI"], "mongodb://mongodb:27017/LibreChat")
        self.assertEqual(env["DOMAIN_CLIENT"], "http://localhost:3080")
        # файл на диске с правами 0600
        self.assertTrue(lc.LC_ENV_FILE.exists())

    def test_write_env_preserves_secrets(self):
        """ГЛАВНЫЙ инвариант: секреты не перегенерируются (иначе учётки/шифрование сломаются)."""
        first = lc._write_env(3080, 3100, [])
        # «обновление» с другим портом и профилями
        second = lc._write_env(4080, 3100, ["rag"],
                               preserve_from=lc.LC_ENV_FILE)
        for key in lc._ENV_SECRET_KEYS:
            self.assertEqual(first[key], second[key],
                             f"секрет {key} изменился при регенерации!")
        self.assertEqual(second["PORT"], "4080")
        self.assertEqual(second["COMPOSE_PROFILES"], "rag")

    def test_patch_env_keys_targeted(self):
        lc._write_env(3080, 3100, [])
        before = lc._parse_env_text(lc.LC_ENV_FILE.read_text())
        ok = lc._patch_env_keys(PORT="5080",
                                DOMAIN_CLIENT="https://example.net:9763",
                                DOMAIN_SERVER="https://example.net:9763")
        self.assertTrue(ok)
        after = lc._parse_env_text(lc.LC_ENV_FILE.read_text())
        self.assertEqual(after["PORT"], "5080")
        self.assertEqual(after["DOMAIN_CLIENT"], "https://example.net:9763")
        # секреты и прочее не тронуты
        for k in lc._ENV_SECRET_KEYS:
            self.assertEqual(before[k], after[k])

    def test_patch_env_keys_noop(self):
        lc._write_env(3080, 3100, [])
        content = lc.LC_ENV_FILE.read_text()
        self.assertTrue(lc._patch_env_keys(PORT="3080"))
        self.assertEqual(lc.LC_ENV_FILE.read_text(), content)

    def test_current_profiles_from_env(self):
        lc._write_env(3080, 3100, ["admin", "bogus"])
        self.assertEqual(lc._current_profiles_from_env(), ["admin"])

    def test_render_env_sections(self):
        text = lc._render_env({"PORT": "3080", "JWT_SECRET": "x" * 48,
                               "MEILI_HOST": "http://meilisearch:7700"})
        self.assertIn("# ── LibreChat core ──", text)
        self.assertIn("# ── Секреты", text)
        self.assertIn("PORT=3080", text)
        self.assertIn("JWT_SECRET=", text)


